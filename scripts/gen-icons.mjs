// Generates src/ui/icons.generated.ts with path data for the Material Symbols the app uses.
// Material Symbols are Apache-2.0 licensed (generic UI icons, not Google product logos).
// Usage: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const names = `
menu search close settings calendar_today mail inbox calendar_month task_alt sticky_note_2 add check
error warning info refresh account_circle logout upload download delete archive star flag reply
reply_all forward attach_file label more_vert arrow_back chevron_left chevron_right edit send drafts
mark_email_unread mark_email_read folder open_in_new description picture_as_pdf image video_call
check_circle radio_button_unchecked lock sync person_add schedule notifications keyboard_arrow_down
keyboard_arrow_up visibility visibility_off palette language privacy_tip contacts drive_file_move
dark_mode light_mode filter_list cloud_off link today event home code
location_on group repeat help view_day view_week view_agenda subject calendar_view_month add_task
`.trim().split(/\s+/)

const dir = 'node_modules/@material-symbols/svg-400/outlined'
const out = {}
for (const n of names) {
  for (const variant of ['', '-fill']) {
    const file = `${dir}/${n}${variant}.svg`
    let svg
    try { svg = readFileSync(file, 'utf8') } catch { if (variant) continue; throw new Error('missing icon ' + n) }
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
    out[n + (variant ? '_fill' : '')] = paths.join(' ')
  }
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: '${v}',`).join('\n')
writeFileSync('src/ui/icons.generated.ts',
  `// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.\n` +
  `export const iconPaths = {\n${body}\n} as const\n\nexport type IconName = keyof typeof iconPaths\n`)
console.log('icons:', Object.keys(out).length)
